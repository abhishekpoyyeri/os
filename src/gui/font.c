extern void vga_putpixel(int x, int y, uint8_t color);

void font_draw_char(int x, int y, char c, uint8_t color) {
    if (c < 32 || c > 126) return;
    
    const uint8_t* glyph = font_data[c - 32];
    
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            if (glyph[row] & (0x80 >> col)) {
                vga_putpixel(x + col, y + row, color);
            }
        }
    }
}

/* Draw a character with a 1px shadow for depth */
void font_draw_char_shadow(int x, int y, char c, uint8_t color, uint8_t shadow) {
    if (c < 32 || c > 126) return;
    const uint8_t* glyph = font_data[c - 32];
    /* Shadow pass */
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            if (glyph[row] & (0x80 >> col)) {
                vga_putpixel(x + col + 1, y + row + 1, shadow);
            }
        }
    }
    /* Foreground pass */
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            if (glyph[row] & (0x80 >> col)) {
                vga_putpixel(x + col, y + row, color);
            }
        }
    }
}

void font_draw_string(int x, int y, const char* str, uint8_t color) {
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += 10;
        } else {
            font_draw_char(cx, y, *str, color);
            cx += 7;  /* Tighter kerning for modern look */
        }
        str++;
    }
}

void font_draw_string_shadow(int x, int y, const char* str, uint8_t fg, uint8_t shadow) {
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += 10;
        } else {
            font_draw_char_shadow(cx, y, *str, fg, shadow);
            cx += 7;
        }
        str++;
    }
}

int font_string_width(const char* str) {
    int w = 0;
    while (*str) {
        if (*str != '\n') w += 7;
        str++;
    }
    return w;
}
